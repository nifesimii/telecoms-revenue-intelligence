// Sample-mode localhost servers; mocked streaming only, no live model calls.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const question = 'Explain this account’s recorded commission, paid amount and outstanding balance. State what remains unverified.';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(10000);
  const requests = [];
  const pending = [];
  const runtimeErrors = [];
  page.on('pageerror', (error) => runtimeErrors.push(error.message));
  await page.route('**/chat', (route) => route.abort());
  await page.route('**/chat/explain', (route) => route.abort());
  await page.route('**/chat/stream', async (route) => {
    requests.push(route.request().postDataJSON());
    const failed = await new Promise((resolve) => pending.push(resolve));
    if (failed) {
      await route.fulfill({ status: 503, json: { detail: 'Temporary test failure. Please retry.' } });
      return;
    }
    await route.fulfill({ contentType: 'application/x-ndjson', body: JSON.stringify({ type: 'complete', response: 'Recorded payment answer', tools_called: [], raw_data: {}, error: null }) + '\n' });
  });
  const waitCount = async (count) => {
    for (let i = 0; i < 100 && requests.length < count; i++) await page.waitForTimeout(50);
    assert.equal(requests.length, count, 'Expected exactly one request per explicit submission');
  };
  const noNewRequest = async (count) => {
    await page.waitForTimeout(200);
    assert.equal(requests.length, count, 'Reopen, rerender, clear and scope changes must not submit');
  };
  const assistant = page.getByRole('region', { name: 'Atlas', exact: true });
  const input = assistant.getByRole('textbox');
  const opener = page.getByRole('button', { name: /^Ask Atlas about this payment$/ });
  const finish = async (index, failed = false) => {
    pending[index](failed);
    await page.waitForFunction(() => !document.querySelector('textarea')?.disabled);
  };
  const assertContext = (request, code = '296065', period = '202606', comparison = '202605') => {
    assert.equal(request.mon_period, period);
    assert.match(request.investigation_context, new RegExp(`Exact dealer account code ${code}`));
    assert.match(request.investigation_context, new RegExp(`Reporting period ${period}`));
    if (comparison) assert.match(request.investigation_context, new RegExp(`Comparison period ${comparison}`));
    assert.match(request.investigation_context, /Payment settlement investigation/);
    assert.match(request.investigation_context, /default/i);
    assert.match(request.investigation_context, /explicit.*partner.*commission/i);
    assert.match(request.investigation_context, /codes/i);
    assert.match(request.investigation_context, /name.*unverified/i);
    assert.doesNotMatch(request.investigation_context, /do not combine other accounts with the same name/);
  };
  await page.goto(process.env.APP_URL || 'http://localhost:5173');
  await page.getByRole('button', { name: 'Payments', exact: true }).click();
  const firstAccount = 'View evidence for River Isle Ventures, 296065';
  await page.getByRole('button', { name: firstAccount, exact: true }).click();
  await noNewRequest(0);
  await opener.focus();
  await opener.press('Enter');
  await waitCount(1);
  await assistant.getByRole('status').waitFor();
  assert.equal(requests[0].message, question);
  assertContext(requests[0]);
  assert.deepEqual(requests[0].conversation_history, []);
  assert.equal(await assistant.getByText(question, { exact: true }).count(), 1);
  const header = assistant.getByText(/River Isle Ventures · Account 296065/);
  assert.match(await header.innerText(), /Jun 2026.*May 2026.*Payments/);
  assert.equal(await input.inputValue(), '');
  assert.equal(await assistant.locator('form').evaluate((el) => el === document.activeElement), true, 'Pending opener focuses the composer form');
  await opener.dblclick();
  await noNewRequest(1);
  // Pending request survives navigation; entering another account does not submit.
  await page.getByRole('button', { name: 'Back to accounts' }).click();
  const otherButtons = page.getByRole('button', { name: /^View evidence for / });
  const secondName = await otherButtons.nth(1).getAttribute('aria-label');
  await otherButtons.nth(1).click();
  await noNewRequest(1);
  await opener.click();
  await waitCount(2);
  const selectedCode = secondName.split(', ').at(-1);
  assertContext(requests[1], selectedCode);
  assert.deepEqual(requests[1].conversation_history, []);
  await finish(1);
  await page.getByRole('button', { name: 'Back to accounts' }).click();
  await page.getByRole('button', { name: firstAccount, exact: true }).click();
  await opener.click();
  await assistant.getByRole('button', { name: 'Working…' }).waitFor();
  await noNewRequest(2);
  await finish(0);
  await assistant.getByText('Recorded payment answer', { exact: true }).waitFor();
  await opener.click();
  assert.equal(await input.inputValue(), '');
  await input.fill('My follow-up draft');
  await opener.click();
  assert.equal(await input.inputValue(), 'My follow-up draft');
  assert.equal(await input.evaluate((el) => el === document.activeElement), true);
  await noNewRequest(2);
  console.log('PASS keyboard opening, clean question/context, one-shot guards, pending navigation and account isolation');

  await input.fill('Retry check');
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await waitCount(3);
  assert.equal(requests[2].message, 'Retry check');
  assertContext(requests[2]);
  assert.equal(requests[2].conversation_history[0].content, question);
  await finish(2, true);
  await assistant.getByRole('alert').waitFor();
  await opener.click();
  assert.equal(await input.inputValue(), '');
  await noNewRequest(3);
  await assistant.getByRole('button', { name: 'Retry explanation' }).click();
  await waitCount(4);
  assert.equal(requests[3].message, 'Retry check');
  assert.equal(requests[3].investigation_context, requests[2].investigation_context);
  await finish(3);
  await assistant.getByText('Recorded payment answer', { exact: true }).nth(1).waitFor();
  console.log('PASS clean follow-up/history, failure and explicit retry with separate context');

  await page.getByLabel('Reporting period').selectOption('202605');
  await opener.waitFor();
  await noNewRequest(4);
  await opener.click();
  await waitCount(5);
  assertContext(requests[4], '296065', '202605', '202604');
  assert.deepEqual(requests[4].conversation_history, []);
  await finish(4);
  await page.getByLabel('Reporting period').selectOption('202606');
  await opener.click();
  await noNewRequest(5);
  assert.equal(await assistant.getByText('Recorded payment answer', { exact: true }).count(), 2);
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await opener.click();
    const rect = await input.boundingBox();
    assert.ok(rect.y >= 0 && rect.y + rect.height <= 900 && rect.x >= 0 && rect.x + rect.width <= width);
    assert.equal(await input.evaluate((el) => el === document.activeElement), true);
    assert.equal(await input.evaluate((el) => { const r = el.getBoundingClientRect(); const main = el.closest('main').getBoundingClientRect(); return r.top >= main.top && r.bottom <= main.bottom && document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2) === el; }), true);
    await header.scrollIntoViewIfNeeded();
    assert.equal(await header.evaluate((el) => el.scrollWidth <= el.clientWidth), true, 'Context header must wrap');
    await page.screenshot({ path: `/tmp/payment-atlas-${width}.png` });
  }
  await page.reload();
  await page.getByRole('button', { name: 'Payments', exact: true }).click();
  await page.getByRole('button', { name: firstAccount, exact: true }).click();
  await opener.click();
  await noNewRequest(5);
  assert.equal(await input.inputValue(), '');
  await input.fill('what products entitle this dealer for commission this month');
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await waitCount(6);
  assert.equal(requests[5].message, 'what products entitle this dealer for commission this month');
  assertContext(requests[5]);
  assert.equal(requests[5].conversation_history[0].content, question);
  await finish(5);
  await assistant.getByRole('button', { name: 'Clear thread' }).click();
  await noNewRequest(6);
  // An existing empty-thread draft is not discarded or auto-submitted by the opener.
  await input.fill('Start again');
  await opener.click();
  assert.equal(await input.inputValue(), 'Start again');
  await noNewRequest(6);
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await waitCount(7);
  assert.equal(requests[6].message, 'Start again');
  assertContext(requests[6]);
  assert.deepEqual(requests[6].conversation_history, []);
  await finish(6, true);
  await opener.click();
  await noNewRequest(7);
  await input.fill('Try a different question');
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await waitCount(8);
  assert.equal(requests[7].message, 'Try a different question');
  assertContext(requests[7]);
  assert.deepEqual(requests[7].conversation_history, []);
  await finish(7);
  await assistant.getByRole('button', { name: 'Clear thread' }).click();
  await noNewRequest(8);
  await opener.click();
  await waitCount(9);
  assert.equal(requests[8].message, question);
  assert.deepEqual(requests[8].conversation_history, []);
  await finish(8);
  console.log('PASS period isolation, responsive context/composer, reload, clear/draft preservation and explicit reopening');

  await page.getByRole('button', { name: 'Commission', exact: true }).click();
  await page.getByRole('button', { name: 'Ask Atlas', exact: true }).click();
  const suggestion = 'Explain the commission change by denomination between these periods.';
  await assistant.getByRole('button', { name: suggestion, exact: true }).click();
  assert.equal(await input.inputValue(), suggestion);
  assert.equal(await input.evaluate((el) => el === document.activeElement), true);
  await noNewRequest(9);
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await waitCount(10);
  assert.equal(requests[9].message, suggestion);
  assert.match(requests[9].investigation_context, /Reporting period 202606/);
  await finish(9);
  assert.deepEqual(runtimeErrors, []);
  console.log('PASS unchanged Commission suggestion behavior, clean opening and no runtime errors');
} finally {
  await browser.close();
}
