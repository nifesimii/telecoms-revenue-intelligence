// Run against sample-mode localhost servers. Set PLAYWRIGHT_MODULE to a Playwright
// index.mjs path if it is not installed locally; no live model calls are made.
import assert from 'node:assert/strict';
import { EventEmitter, once } from 'node:events';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const question = 'Explain this account’s recorded commission, paid amount and outstanding balance. State what remains unverified.';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const requests = [];
  const captured = new EventEmitter();
  const nextRequest = () => once(captured, 'request', { signal: AbortSignal.timeout(10000) });
  let release;
  let failNext = false;
  const runtimeErrors = [];
  page.on('pageerror', (error) => runtimeErrors.push(error.message));
  await page.route('**/chat', async (route) => {
    requests.push(route.request().postDataJSON());
    await new Promise((resolve) => { release = resolve; captured.emit('request'); });
    if (failNext) {
      failNext = false;
      await route.fulfill({ status: 503, json: { detail: 'Temporary test failure. Please retry.' } });
      return;
    }
    await route.fulfill({ json: { response: 'Recorded payment answer', tools_called: [], raw_data: {}, error: null } });
  });
  await page.goto(process.env.APP_URL || 'http://localhost:5173');
  await page.getByRole('button', { name: 'Payments', exact: true }).click();
  await page.getByRole('button', { name: 'View evidence for River Isle Ventures, 296065', exact: true }).click();
  const opener = page.getByRole('button', { name: /^Ask Atlas about this payment$/ });
  await opener.click();
  const assistant = page.getByRole('region', { name: 'Atlas', exact: true });
  const input = assistant.getByRole('textbox');
  await input.waitFor();
  await page.waitForFunction((text) => document.querySelector('textarea')?.value === text, question);
  assert.equal(await input.inputValue(), question, 'Opener must prefill payment question');
  assert.equal(await input.evaluate((el) => el === document.activeElement), true, 'Composer must receive focus');
  const rect = await input.boundingBox();
  assert.ok(rect.y >= 0 && rect.y + rect.height <= 900, 'Composer must be visible');
  assert.equal(requests.length, 0, 'Opening must not submit');
  console.log('PASS first-click prefill, focus, visibility and explicit submission');
  await input.fill('Explain my edited payment question.');
  await opener.scrollIntoViewIfNeeded();
  await opener.focus();
  await opener.press('Enter');
  assert.equal(await input.inputValue(), 'Explain my edited payment question.');
  assert.equal(await input.evaluate((el) => el === document.activeElement), true);
  assert.equal(requests.length, 0);
  const capture = nextRequest();
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await capture;
  await assistant.getByRole('status').waitFor();
  assert.equal(requests.length, 1);
  assert.equal(requests[0].mon_period, '202606');
  assert.match(requests[0].message, /Comparison period 202605/);
  assert.match(requests[0].message, /Exact dealer account code 296065/);
  assert.match(requests[0].message, /Payment settlement investigation/);
  assert.deepEqual(requests[0].conversation_history, []);
  await page.getByRole('button', { name: 'Back to accounts' }).click();
  // Accessible name contains the account; select a different row explicitly.
  const otherButtons = page.getByRole('button', { name: /^View evidence for / });
  const secondName = await otherButtons.nth(1).getAttribute('aria-label');
  await otherButtons.nth(1).click();
  await opener.click();
  assert.equal(await assistant.getByText('Explain my edited payment question.', { exact: false }).count(), 0);
  assert.equal(await assistant.getByRole('button', { name: 'Working…' }).count(), 0);
  await page.getByRole('button', { name: 'Back to accounts' }).click();
  await page.getByRole('button', { name: 'View evidence for River Isle Ventures, 296065', exact: true }).click();
  await opener.click();
  await assistant.getByRole('button', { name: 'Working…' }).waitFor();
  release();
  await assistant.getByText('Recorded payment answer', { exact: true }).waitFor();
  await opener.click();
  assert.equal(await assistant.getByText('Recorded payment answer', { exact: true }).count(), 1);
  console.log('PASS keyboard/draft preservation, exact request, pending navigation and dealer isolation', secondName);
  failNext = true;
  await input.fill('Retry check');
  const failureCapture = nextRequest();
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await assistant.getByRole('button', { name: 'Working…' }).waitFor();
  await page.waitForFunction(() => document.querySelector('textarea')?.disabled);
  await failureCapture;
  release();
  await assistant.getByRole('alert').waitFor();
  assert.match(await assistant.getByRole('alert').innerText(), /Please retry/);
  const retryCapture = nextRequest();
  await opener.click();
  await assistant.getByRole('button', { name: 'Send question' }).click();
  await retryCapture;
  release();
  await page.waitForFunction(() => !document.querySelector('textarea')?.disabled);
  await assistant.getByText('Recorded payment answer', { exact: true }).nth(1).waitFor();
  assert.equal(await assistant.getByRole('alert').count(), 0);
  assert.equal(requests.length, 3);
  console.log('PASS actionable failure and explicit retry');
  await page.getByLabel('Reporting period').selectOption('202605');
  await opener.click();
  assert.equal(await assistant.getByText('Recorded payment answer', { exact: true }).count(), 0);
  await page.getByLabel('Reporting period').selectOption('202606');
  await opener.click();
  assert.equal(await assistant.getByText('Recorded payment answer', { exact: true }).count(), 2);
  await page.setViewportSize({ width: 320, height: 844 });
  await opener.click();
  await page.waitForFunction(() => { const input = document.querySelector('textarea'); return input?.value && !input.disabled && !input.form.querySelector('button').disabled; });
  const narrow = await input.boundingBox();
  assert.ok(narrow.y >= 0 && narrow.y + narrow.height <= 844 && narrow.x >= 0 && narrow.x + narrow.width <= 320);
  assert.equal(await input.evaluate((el) => el === document.activeElement), true);
  assert.equal(await input.evaluate((el) => { const r = el.getBoundingClientRect(); const main = el.closest('main').getBoundingClientRect(); return r.top >= main.top && r.bottom <= main.bottom && document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2) === el; }), true, 'Composer must clear the header and scrollable ancestor clipping');
  await page.screenshot({ path: '/tmp/payment-composer-narrow.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await opener.click();
  await page.screenshot({ path: '/tmp/payment-composer-desktop.png' });
  console.log('PASS reporting-period isolation and narrow/desktop composer visibility');
  await page.getByRole('button', { name: 'Commission', exact: true }).click();
  await page.getByRole('button', { name: 'Ask Atlas', exact: true }).click();
  const commission = page.getByRole('region', { name: 'Atlas', exact: true });
  await commission.getByRole('button', { name: 'Explain the commission change by denomination between these periods.', exact: true }).click();
  assert.equal(await commission.getByRole('textbox').inputValue(), 'Explain the commission change by denomination between these periods.');
  assert.equal(await commission.getByRole('textbox').evaluate((el) => el === document.activeElement), true);
  assert.equal(requests.length, 3);
  assert.deepEqual(runtimeErrors, []);
  console.log('PASS Commission suggestion behavior and no runtime errors');
} finally {
  await browser.close();
}
